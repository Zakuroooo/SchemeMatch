"""Generate supabase/seed.sql from the golden scheme files.

usage: python3 pipeline/scripts/make_seed.py
The golden JSON files are the source of truth; seed.sql is generated, never hand-edited.
Schemes are seeded as 'live' for LOCAL DEVELOPMENT ONLY (they are AI-checked, not yet
human-reviewed; see docs/EVALS.md). Production seeding is decided at deploy time.
"""
import json
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GOLDEN = ROOT / "pipeline/golden/schemes"
OUT = ROOT / "supabase/seed.sql"
NS = uuid.UUID("5c4e3e1a-6b1d-4c8e-9a52-7d1f0b2e9c11")  # fixed namespace → stable ids


def lit(v):
    """SQL literal: strings quoted with '' escaping, None → null, json → ::jsonb."""
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (dict, list)):
        return "'" + json.dumps(v, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def source_hash(scheme):
    for line in (ROOT / "pipeline" / scheme["source_file"]).read_text().splitlines()[:6]:
        if line.startswith("# sha256 of the text below: "):
            return "sha256:" + line.split(": ", 1)[1]
    raise SystemExit(f"{scheme['slug']}: no sha256 header in its source file")


def main():
    files = sorted(GOLDEN.glob("*.json"))
    out = ["-- GENERATED by pipeline/scripts/make_seed.py from pipeline/golden/schemes. Do not edit.",
           "-- Local development seed: schemes are 'live' here only.", "begin;", ""]
    for f in files:
        s = json.loads(f.read_text())
        sid = uuid.uuid5(NS, f"scheme:{s['slug']}")
        rid = uuid.uuid5(NS, f"rules:{s['slug']}:1")
        t = s["text"]["en"]
        out += [f"-- {s['slug']}",
                "insert into public.schemes (id, slug, level, state, category, official_url, source_hash, last_checked, status) values "
                f"({lit(str(sid))}, {lit(s['slug'])}, {lit(s['level'])}, {lit(s['state'])}, {lit(s['category'])}, "
                f"{lit(s['official_url'])}, {lit(source_hash(s))}, '2026-10-19', 'live');",
                "insert into public.scheme_texts (scheme_id, lang, title, benefit, how_to_apply) values "
                f"({lit(str(sid))}, 'en', {lit(t['title'])}, {lit(t['benefit'])}, {lit(t['how_to_apply'])});"]
        for d in s.get("documents", []):
            out.append("insert into public.scheme_documents (scheme_id, doc_key, mandatory, condition) values "
                       f"({lit(str(sid))}, {lit(d['key'])}, {lit(d['mandatory'])}, {lit(d.get('when'))});")
        out += ["insert into public.scheme_rule_versions (id, scheme_id, version, rule_format_version, eligibility, unmodelled, ambiguous, source_quote_check_passed) values "
                f"({lit(str(rid))}, {lit(str(sid))}, 1, 1, {lit(s['eligibility'])}, {lit(s['unmodelled'])}, {lit(s['ambiguous'])}, true);",
                f"update public.schemes set current_rule_version_id = {lit(str(rid))} where id = {lit(str(sid))};", ""]
    out.append("commit;")
    OUT.write_text("\n".join(out) + "\n")
    assert len(files) == 15, f"expected 15 golden schemes, found {len(files)}"
    print(f"wrote {OUT.relative_to(ROOT)} with {len(files)} schemes")


if __name__ == "__main__":
    main()
