"""Generate golden/VERIFY.md: a human checklist for every golden rule.

usage: python3 pipeline/scripts/make_verify.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LABEL = {
    "age": "Age", "gender": "Gender", "marital_status": "Marital status",
    "annual_family_income": "Annual family income (₹)", "caste_category": "Caste category",
    "land_acres": "Land owned (acres)", "disability_percent": "Disability (%)",
    "has_bpl_card": "On the BPL list", "is_pregnant_or_lactating": "Pregnant or breastfeeding",
    "state": "State", "district": "District", "occupation": "Occupation", "is_student": "Is a student",
    "education_level": "Education", "household_size": "Household size", "children_count": "Children",
}
OP = {"eq": "is", "neq": "is not", "in": "is one of", "not_in": "is not one of", "lt": "is less than",
      "lte": "is at most", "gt": "is more than", "gte": "is at least", "between": "is between"}


def say(c):
    v = c["value"]
    if c["op"] == "between":
        v = f"{v[0]} and {v[1]} (both included)"
    elif isinstance(v, bool):
        return f"{LABEL[c['field']]}: {'yes' if v else 'no'}"
    elif isinstance(v, list):
        v = ", ".join(map(str, v))
    elif isinstance(v, (int, float)) and c["field"] == "annual_family_income":
        v = f"₹{v:,}"
    return f"{LABEL[c['field']]} {OP[c['op']]} {v}"


def rows(node, depth=0, out=None):
    out = [] if out is None else out
    pad = "&nbsp;&nbsp;&nbsp;&nbsp;" * max(depth - 1, 0)
    if "field" in node:
        out.append((pad + say(node), node["source_quote"]))
    else:
        kind = "ALL of these must be true" if "all" in node else "AT LEAST ONE of these must be true"
        if depth > 0 or len(node.get("all", node.get("any", []))) > 1:
            out.append((pad + f"**{kind}:**", ""))
        for ch in node.get("all", node.get("any", [])):
            rows(ch, depth + 1, out)
    return out


def main():
    lines = ["# Golden set — human verification checklist", "",
             "*Generated by `pipeline/scripts/make_verify.py`. Do not edit by hand; re-run the script.*", "",
             "**Status (2026-10-19):** every quote is machine-checked against its saved source; every rule's meaning was checked by Claude after a full read of each source. **Human review is still pending**, so this is an AI-drafted, AI-checked set, not yet a human golden set.", "",
             "**How to check one scheme (~5 min):**",
             "1. Open the **saved copy** link (always works) and, if it loads, the official page.",
             "2. For each row, press Ctrl+F (Cmd+F) and paste the quote. Then read the plain-English rule: is the number right? Is \"at least / at most / less than\" right? Is AND vs OR right?",
             "3. Tick the box (`- [ ]` → `- [x]`), or leave a PR comment on the row that is wrong.",
             "4. When every row of a scheme is ticked, tell Claude: it records `reviewed_by` and `reviewed_at`.", ""]
    for f in sorted((ROOT / "golden/schemes").glob("*.json")):
        s = json.loads(f.read_text())
        lines += [f"## {s['text']['en']['title']} (`{s['slug']}`)", "",
                  f"Saved copy: [{s['source_file']}](../{s['source_file']}) · Official page: <{s['official_url']}>", ""]
        for rule, quote in rows(s["eligibility"]):
            lines.append(f"- [ ] {rule} — quote: \"{quote}\"" if quote else f"- {rule}")
        if s["unmodelled"]:
            lines += ["", "*Not modelled as rules (shown to users as \"you must also confirm\"):*"]
            lines += [f"- [ ] {u['text']} — quote: \"{u['source_quote']}\"" for u in s["unmodelled"]]
        if s["ambiguous"]:
            lines += ["", "*Flagged as unclear (excluded from accuracy):*"]
            lines += [f"- {a}" for a in s["ambiguous"]]
        lines += ["", f"Meaning checked by: {s.get('meaning_checked_by') or '—'} ({s.get('meaning_checked_at') or 'not yet'}) · Human reviewer: {s['reviewed_by'] or 'not yet'}", ""]
    (ROOT / "golden/VERIFY.md").write_text("\n".join(lines))
    print("wrote golden/VERIFY.md")


if __name__ == "__main__":
    main()
